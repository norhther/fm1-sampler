#!/usr/bin/env python3
"""Generate engine/dsp/DrumXKits.h from JIANT's firmware/src/drumx_voice.c (DX_KITS: 9 kits of 8 lanes).
usage: gen_drumx_kits.py path/to/drumx_voice.c"""
import re, sys
src = open(sys.argv[1]).read()
body = src[src.index('static const dx_kit_t DX_KITS[]'):src.index('#define DX_NKIT')]
W = {'DXW_SINE': 0, 'DXW_FM': 1, 'DXW_METAL': 2, 'DXW_BELL': 3}; F = {'DXF_LP': 0, 'DXF_BP': 1, 'DXF_HP': 2}
M = {'DXM_DECAY': 0, 'DXM_LONG': 1, 'DXM_NOISE': 2, 'DXM_SINE': 3}
kits = []
for blk in re.split(r'\{\s*/\* ', body)[1:]:
    name = blk[:blk.index('*/')].strip()
    lanes = []
    for m in re.finditer(r'\{DX_MODE\((\w+), (\w+), (\d)\)((?: \| [\w ]+(?:<< 5)?)*), \{([\d, ]+)\}, \{([\d, ]+)\}\}', blk):
        w, f, snap, extra, a, b = m.groups()
        mode = W[w] | F[f] << 2 | int(snap) << 4
        if 'DX_DRIVE' in extra: mode |= 0x80
        pm = re.search(r'(DXM_\w+) << 5', extra)
        if pm: mode |= M[pm.group(1)] << 5
        lanes.append((mode, a.strip(), b.strip()))
    assert len(lanes) == 8, (name, len(lanes))
    kits.append((name, lanes))
out = ['// SPDX-License-Identifier: GPL-3.0-only', '// generated by tools/gen_drumx_kits.py from JIANT (FELUCCA TONIC) drumx_voice.c: its 9 factory DRUM-X kits.',
       '// A lane: mode (wave 0..1, filter bits 2-3, snap bit 4, pitch mod bits 5-6, drive bit 7), then patches A and B: PITCH PMOD DECAY NOISE COLOR.',
       '#pragma once', '#include <cstdint>', 'struct DrumXLane { uint8_t mode, a[5], b[5]; };',
       f'constexpr int kDrumXKitCount = {len(kits)};', 'struct DrumXKit { const char* name; DrumXLane lane[8]; };', 'static const DrumXKit kDrumXKits[kDrumXKitCount] = {']
for name, lanes in kits:
    out.append('    {"%s", {' % name.title())
    for mode, a, b in lanes: out.append('        {%d, {%s}, {%s}},' % (mode, a, b))
    out.append('    }},')
out.append('};')
open('engine/dsp/DrumXKits.h', 'w').write('\n'.join(out) + '\n')
print(len(kits), 'kits')
