#!/usr/bin/env python3
"""Generate engine/dsp/OracleSounds.h from Tessera's firmware/src/eng_oracle.c (the OR_ enum) and oracle_sounds.h (24 sounds).
usage: gen_oracle_sounds.py path/to/tessera/firmware/src"""
import re, sys
d = sys.argv[1]
eng = open(d + '/eng_oracle.c').read()
enum = eng[eng.index('enum {                           /* the patch'):]
enum = enum[:enum.index('};')]
names = [n for n in re.findall(r'\b(OR_[A-Z0-9_]+)\b', enum) if n != 'OR_N']
idx = {n: i for i, n in enumerate(names)}
src = open(d + '/oracle_sounds.h').read()
pre = re.findall(r'OR_PRE\("([^"]+)", (\d)\)', src)
body = src[src.index('static const or_sound_t OR_SOUNDS[]'):]
sounds = re.findall(r'\{\{(.*?)\}\},\s*/\*|\{\{\{0, 0\}\}\},', body, re.S)
entries = re.split(r'/\* [A-Z0-9 ]+ \*/', body)
rows = []
for e in entries:
    sets = re.findall(r'S\((OR_[A-Z0-9_]+), (\d+)\)', e)
    if sets or 'INIT' in e or not rows and '{0, 0}' in e: rows.append([(idx[k], int(v)) for k, v in sets])
rows = rows[:len(pre)]
assert len(rows) == len(pre), (len(rows), len(pre))
out = ['// SPDX-License-Identifier: GPL-3.0-only', '// generated by tools/gen_oracle_sounds.py from Tessera (GPL-3.0, Theo Dainis): ORACLE\'s patch layout and its 24 sounds.',
       '// A sound is a few (index, value) pairs over INIT; the index is the Prophet panel order below, values 0..127 (switches 0/1).', '#pragma once', '#include <cstdint>',
       f'constexpr int kOracleN = {len(names)};', 'enum OrParam {' + ', '.join(names) + '};', f'constexpr int kOracleSoundCount = {len(pre)};',
       'struct OracleSet { uint8_t k, v; };', 'struct OracleSound { const char* name; bool mono; int n; OracleSet set[24]; };', 'static const OracleSound kOracleSounds[kOracleSoundCount] = {']
for (nm, mono), r in zip(pre, rows):
    out.append('    {"%s", %s, %d, {%s}},' % (nm.title(), 'true' if mono == '1' else 'false', len(r), ', '.join('{%d, %d}' % kv for kv in r)))
out.append('};')
open('engine/dsp/OracleSounds.h', 'w').write('\n'.join(out) + '\n')
print(len(names), 'params', len(pre), 'sounds')
