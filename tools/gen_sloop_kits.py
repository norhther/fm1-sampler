"""engine/dsp/SloopKits.h: SLOOP's synthesised drum kits (isod89/sloop-fm1, GPL-3.0, on Felucca by Leo Kuroshita) as float tables
in musical units (Hz, ms, octaves, dB), read by engine/dsp/SloopDrum.h.
usage: tools/gen_sloop_kits.py <sloop-fm1>/tools/gen_drumkits.py engine/dsp/SloopKits.h"""
import copy, importlib.util, json, sys
from pathlib import Path

spec = importlib.util.spec_from_file_location("gdk", sys.argv[1]); g = importlib.util.module_from_spec(spec); spec.loader.exec_module(g)
levels = json.loads(g.LEVELS_FILE.read_text()) if g.LEVELS_FILE.exists() else {}
def f(x):
    t = f"{float(x):.6g}"
    return t + (".0f" if all(c not in t for c in ".en") else "f")
L = ["// generated by tools/gen_sloop_kits.py from SLOOP's tools/gen_drumkits.py (GPL-3.0-only)", "#pragma once", "#include \"SloopDrum.h\"",
     f"constexpr int kSloopKitCount = {len(g.KITS)};", "static const SloopKit kSloopKits[kSloopKitCount] = {"]
for name, style, crush, k in g.KITS:
    k = g.punch(copy.deepcopy(k))
    L.append(f'    {{"{name}", "{style}", {crush}, {{')
    for lane in g.LANES:
        s = k[lane]; flt = s["filt"]
        mode = g.FMODE[flt[0]] if flt else 0; res = flt[2] if flt else 0.0; allf = 1 if flt and "all" in flt[3:] else 0
        lev = s["level"] + levels.get(name, {}).get(lane, 0.0)
        v = [g.WAVE[s["wave"]], g.SRC[s["src"]], s["hz"], s["bend"], s["bt"], s["hold"], s["decay"], s["tlev"] if s["wave"] else 0, s["t2"], s["t2lev"],
             s["click"], s["nlev"] if s["src"] else 0, s["nhold"], s["ndec"], mode, flt[1] if flt else 16000, res, allf, s["fenv"], s["hpf"] or 0, s["chip"] or 0, s["drive"], lev]
        L.append("        {" + ", ".join(str(int(x)) if i < 2 or i in (14, 17) else f(x) for i, x in enumerate(v)) + "},   // " + lane)
    L.append("    }},")
L.append("};")
Path(sys.argv[2]).write_text("\n".join(L) + "\n")
print(len(g.KITS), "kits")
